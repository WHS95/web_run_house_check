import { describe, it, expect } from 'vitest';
import { 마스터메시지 } from './messages';

describe('master 메시지', () => {
    describe('정적 메시지', () => {
        it('인증실패 메시지', () => {
            expect(마스터메시지.인증실패).toBe('인증되지 않은 사용자입니다.');
        });
        it('권한실패 메시지', () => {
            expect(마스터메시지.권한실패).toBe('마스터 관리자 권한이 필요합니다.');
        });
        it('크루이름중복 메시지', () => {
            expect(마스터메시지.크루이름중복).toBe('이미 존재하는 크루 이름입니다.');
        });
        it('크루없음 메시지', () => {
            expect(마스터메시지.크루없음).toBe('존재하지 않는 크루입니다.');
        });
        it('저장실패 메시지', () => {
            expect(마스터메시지.저장실패).toBe('저장 중 오류가 발생했습니다.');
        });
    });

    describe('동적 메시지', () => {
        it('크루생성성공은 크루 이름을 포함', () => {
            expect(마스터메시지.크루생성성공('한강 러닝')).toBe(
                '크루 "한강 러닝"이(가) 생성되었습니다.'
            );
        });
        it('크루수정성공은 크루 이름을 포함', () => {
            expect(마스터메시지.크루수정성공('A')).toBe(
                '크루 "A" 정보가 수정되었습니다.'
            );
        });
        it('삭제성공은 크루 이름을 포함', () => {
            expect(마스터메시지.삭제성공('B크루')).toBe(
                '크루 "B크루"이(가) 비활성화되었습니다.'
            );
        });
        it('빈 이름도 허용 (호출자 책임)', () => {
            expect(마스터메시지.크루생성성공('')).toBe('크루 ""이(가) 생성되었습니다.');
        });
    });
});
